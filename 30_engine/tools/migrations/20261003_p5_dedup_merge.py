def curly_quotes(s: str) -> str:
    """「」→“”，『』→‘’；「」落在“”里面时用单引号，保持中文引号嵌套规则。"""
    out, stack = [], []
    for ch in s:
        if ch == "“":
            stack.append("“")
            out.append(ch)
        elif ch == "”":
            if stack:
                stack.pop()
            out.append(ch)
        elif ch == "「":
            inner = "“" in stack
            stack.append("‘" if inner else "“")
            out.append(stack[-1])
        elif ch == "」":
            opened = stack.pop() if stack else "“"
            out.append("’" if opened == "‘" else "”")
        elif ch == "『":
            out.append("‘")
        elif ch == "』":
            out.append("’")
        else:
            out.append(ch)
    return "".join(out)


def main():
    files = {f: [json.loads(l) for l in f.read_text(encoding="utf-8").splitlines() if l.strip()]
             for f in sorted(common.qa_dir().glob("c[1-6]_*.jsonl"))}
    recs = {r["id"]: r for rs in files.values() for r in rs}
    log = []

    for m in MERGES:
        keep, drop = recs[m["keep"]], recs[m["drop"]]
        if drop["status"] == "deprecated":
            continue
        for k in ("question", "answer", "tags", "question_keywords", "scenarios", "source_anchor", "derives_from"):
            keep[k] = m[k]
        drop["status"] = "deprecated"
        for r in (keep, drop):
            r["updated"] = TODAY
        log.append(f"合并 {m['drop']} → {m['keep']}")

    for rid, qs in QUESTION_EDITS.items():
        new = " / ".join(qs)
        if recs[rid]["question"] != new:
            recs[rid]["question"] = new
            recs[rid]["updated"] = TODAY
            log.append(f"改问法 {rid}")
    for rid, kws in KEYWORD_EDITS.items():
        if recs[rid]["question_keywords"] != kws:
            recs[rid]["question_keywords"] = kws
            recs[rid]["updated"] = TODAY

    quoted = []
    for r in recs.values():
        changed = False
        for k in TEXT_FIELDS:
            new = curly_quotes(r[k])
            if new != r[k]:
                r[k] = new
                changed = True
        if changed:
            r["updated"] = TODAY
            quoted.append(r["id"])
    if quoted:
        log.append(f"引号统一 {len(quoted)} 条：{' '.join(quoted)}")

    errors = []
    for r in recs.values():
        r["answer_hash"] = answer_hash(r["answer"])
        errors += [f"{r['id']}: {e}" for e in validate_record(r)]
    if errors:
        raise SystemExit("校验未过，终止且未写任何文件：\n" + "\n".join(errors))

    for f, rs in files.items():
        tmp = f.with_suffix(".jsonl.tmp")
        tmp.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rs) + "\n", encoding="utf-8")
        tmp.replace(f)
    print("\n".join(log) or "无变化（已处置过）")


if __name__ == "__main__":
    common.force_utf8_stdout()
